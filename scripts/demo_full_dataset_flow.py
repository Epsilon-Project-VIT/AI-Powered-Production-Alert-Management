"""Generate a full, offline-safe Stage 1-4 demonstration from the Excel dataset.

Historical Priority and Assignment group fields are removed before inference.
Stage 4 telemetry is synthetic and is labelled as mock in the report.
"""
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from alert_management.config.settings import Settings
from alert_management.stage1_ingestion.adapters.excel_adapter import ExcelAlertAdapter
from alert_management.stage1_ingestion.cleaners.field_cleaner import FieldCleaner
from alert_management.stage1_ingestion.cleaners.normalizer import Normalizer
from alert_management.stage1_ingestion.pipeline import Stage1Pipeline
from alert_management.stage1_ingestion.validators.alert_validator import AlertValidator
from alert_management.stage2_classification.models.tfidf_lr import TfidfLogisticClassifier
from alert_management.stage2_classification.pipeline import ClassificationPipeline
from alert_management.stage3_correlation.clustering.semantic_clusterer import SemanticClusterer
from alert_management.stage3_correlation.clustering.signature_matcher import SignatureMatcher
from alert_management.stage3_correlation.pipeline import CorrelationPipeline
from alert_management.stage4_analysis.pipeline import Stage4Pipeline
from alert_management.stage4_analysis.reasoning.mock_reasoning_provider import MockReasoningProvider
from alert_management.stage4_analysis.telemetry.mock_log_provider import MockLogProvider
from alert_management.stage4_analysis.telemetry.mock_metric_provider import MockMetricProvider
from alert_management.stage4_analysis.telemetry.mock_trace_provider import MockTraceProvider


def stage2_rationale(alert, prediction, task):
    """A transparent explanation of the input/provenance, not hidden LLM reasoning."""
    return (
        f"{task} is an ML prediction derived from the arrival-time client and normalized "
        f"description only; it is not an observed fact. Provider={prediction.provider}; "
        f"model={prediction.model or 'priority/routing_tfidf_lr'}."
    )


def main():
    stage1 = Stage1Pipeline(
        FieldCleaner(exclude_fields=Settings.EXCLUDE_FIELDS),
        Normalizer(patterns=Settings.NORMALIZATION_PATTERNS),
        AlertValidator(required_fields=Settings.REQUIRED_FIELDS),
    )
    # This is the production-safe ingestion mode: target/outcome fields are removed.
    alerts = stage1.run(ExcelAlertAdapter(
        Settings.EXCEL_FILE_PATH,
        Settings.EXCEL_COLUMN_MAPPING,
        forbidden_metadata_fields=set(Settings.FORBIDDEN_METADATA_FIELDS),
    ))

    priority_model = TfidfLogisticClassifier(model_name="priority_tfidf_lr")
    routing_model = TfidfLogisticClassifier(model_name="routing_tfidf_lr")
    priority_model.load(Settings.STAGE2_MODELS_DIR)
    routing_model.load(Settings.STAGE2_MODELS_DIR)
    stage2 = ClassificationPipeline(priority_model=priority_model, routing_model=routing_model)
    enriched_alerts = stage2.classify_batch(alerts)

    correlation = CorrelationPipeline(
        signature_matcher=SignatureMatcher(min_group_size=2),
        semantic_clusterer=SemanticClusterer(
            embedding_model="all-MiniLM-L6-v2", min_cluster_size=2, min_samples=1
        ),
        max_time_gap_hours=24.0,
        min_correlation_score=0.7,
    )
    incident_groups, uncorrelated_alerts = correlation.correlate_alerts(enriched_alerts)

    stage4 = Stage4Pipeline(
        log_provider=MockLogProvider(seed=42),
        metric_provider=MockMetricProvider(seed=42),
        trace_provider=MockTraceProvider(seed=42),
        reasoning_provider=MockReasoningProvider(),
    )
    incident_results = []
    for index, incident in enumerate(incident_groups, 1):
        rca, support_message, stakeholder_message = stage4.analyze_incident(incident, enriched_alerts)
        incident_results.append({
            "candidate_incident": incident.model_dump(mode="json"),
            "correlation_explanation": (
                "Candidate grouping generated by deterministic exact-signature/semantic, "
                "time, client, service, and Stage 2 compatibility signals. This is not accuracy "
                "and has no incident-ground-truth claim."
            ),
            "rca": rca.model_dump(mode="json"),
            "evidence": [e.model_dump(mode="json") for e in rca.evidence],
            "recommendations_policy_status": "HUMAN / POLICY APPROVAL REQUIRED; no actions executed.",
            "support_communication": support_message,
            "stakeholder_communication": stakeholder_message,
        })
        print(f"Stage 4 {index}/{len(incident_groups)}: {incident.incident_id}", flush=True)

    alert_results = []
    for alert in enriched_alerts:
        assert not set((alert.metadata or {})) & set(Settings.FORBIDDEN_METADATA_FIELDS)
        alert_results.append({
            "alert_id": alert.alert_id,
            "created_at": alert.created_at.isoformat(),
            "client": alert.client,
            "arrival_time_input": {
                "raw_description": alert.raw_description,
                "normalized_description": alert.normalized_description,
                "metadata": alert.metadata,
            },
            "stage2": {
                "priority": alert.priority.model_dump(),
                "priority_explanation": stage2_rationale(alert, alert.priority, "Priority"),
                "routing": alert.routing.model_dump(),
                "routing_explanation": stage2_rationale(alert, alert.routing, "Routing"),
            },
        })

    report = {
        "scope": "All Excel alerts, full offline-safe Stage 2-4 demonstration",
        "provenance": {
            "stage2": "model_prediction (TF-IDF Logistic Regression; not ground truth)",
            "stage3": "experimental deterministic candidate grouping; no correlation accuracy claim",
            "stage4": "mock telemetry / mock reasoning only; no real production telemetry asserted",
            "remediation": "recommendations only; HUMAN / POLICY APPROVAL REQUIRED",
        },
        "counts": {
            "alerts_classified": len(enriched_alerts),
            "candidate_incidents": len(incident_groups),
            "uncorrelated_alerts": len(uncorrelated_alerts),
        },
        "alerts": alert_results,
        "candidate_incidents": incident_results,
        "uncorrelated_alert_ids": [alert.alert_id for alert in uncorrelated_alerts],
    }
    output = Settings.DATA_DIR / "full_dataset_flow_report.json"
    output.write_text(json.dumps(report, indent=2, default=str))
    print(json.dumps({"output": str(output), "counts": report["counts"]}))


if __name__ == "__main__":
    main()
